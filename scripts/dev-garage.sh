#!/usr/bin/env bash
# Disposable local Garage for live tests (contract suite + Playwright E2E).
#
# Wraps scripts/live-tests/* (the same provisioning CI uses) with local defaults:
# a single `garage-dev` container on the host network (S3 :3900, admin :3903),
# freshly generated secrets, and a gitignored env file holding everything the
# live suites need. Every `up` recreates the container, so state never leaks
# between runs.
#
#   scripts/dev-garage.sh up         start + provision, write .env.garage-dev.local
#   scripts/dev-garage.sh e2e [...]  run `pnpm e2e` against it (args go to Playwright)
#   scripts/dev-garage.sh contract   run the Bucket Backend API contract suite
#   scripts/dev-garage.sh env        print the env file (for `set -a; . <file>`)
#   scripts/dev-garage.sh logs       tail the Garage container logs
#   scripts/dev-garage.sh down       remove the container and the env file
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

export GARAGE_CONTAINER_NAME="${GARAGE_CONTAINER_NAME:-garage-dev}"
export GARAGE_IMAGE="${GARAGE_IMAGE:-dxflrs/garage:v2.2.0}"
env_file="$root/.env.garage-dev.local"

die() {
  echo "dev-garage: $*" >&2
  exit 1
}

require_env_file() {
  [[ -f "$env_file" ]] || die "no $env_file; run '$0 up' first"
  docker inspect "$GARAGE_CONTAINER_NAME" >/dev/null 2>&1 ||
    die "container $GARAGE_CONTAINER_NAME is not running; run '$0 up' first"
  set -a
  # shellcheck disable=SC1090
  . "$env_file"
  set +a
}

# Playwright reuses an already-running dev server outside CI, which would test
# a server with a different ADMIN_PASSWORD / DATA_DIR. Refuse instead.
require_free_ports() {
  local port
  for port in "$@"; do
    if (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null; then
      die "port $port is already in use; stop the running dev server first"
    fi
  done
}

cmd_up() {
  command -v docker >/dev/null || die "docker is required"

  export RPC_SECRET ADMIN_TOKEN
  RPC_SECRET="$(openssl rand -hex 32)"
  ADMIN_TOKEN="$(openssl rand -base64 32)"
  export TEST_S3_REGION=garage TEST_S3_BUCKET=s3-browser-test

  local keys
  keys="$(scripts/live-tests/start-garage.sh bucket-api | grep -E '^TEST_S3_(ACCESS|SECRET)_KEY=')"

  local admin_password jwt_secret encryption_key
  admin_password="$(openssl rand -hex 12)"
  jwt_secret="$(openssl rand -hex 32)"
  encryption_key="$(openssl rand -hex 16)" # exactly 32 bytes

  umask 077
  cat >"$env_file" <<EOF
# Generated by scripts/dev-garage.sh up — do not edit; regenerated on every run.
# BFF secrets (shared by the Admin BFF under E2E and the S3 Browser BFF under contract tests)
ADMIN_PASSWORD=$admin_password
JWT_SECRET=$jwt_secret
ENCRYPTION_KEY=$encryption_key
LOG_LEVEL=warn
MORGAN_FORMAT=off

# E2E (e2e/fixtures.ts)
TEST_GARAGE_ENDPOINT=http://localhost:3903
TEST_GARAGE_ADMIN_TOKEN=$ADMIN_TOKEN

# Contract suite (packages/bucket-api-contract-tests)
TEST_BFF_URL=http://localhost:3002/api
TEST_BFF_PASSWORD=$admin_password
TEST_S3_ENDPOINT=http://localhost:3900
TEST_S3_REGION=$TEST_S3_REGION
TEST_S3_FORCE_PATH_STYLE=true
TEST_S3_BUCKET=$TEST_S3_BUCKET
$keys
EOF

  echo
  echo "Garage is up: S3 http://localhost:3900 · admin http://localhost:3903"
  echo "Env written to ${env_file#"$root"/} — next: '$0 e2e' or '$0 contract'"
}

cmd_e2e() {
  require_env_file
  require_free_ports 3001 5173
  # The web apps resolve @garage/* through their built dist (as in CI).
  pnpm build:packages
  # A fresh, empty admin DB per run keeps the E2E deterministic.
  DATA_DIR="$(mktemp -d -t garage-admin-e2e.XXXXXX)"
  export DATA_DIR
  echo "DATA_DIR=$DATA_DIR"
  pnpm e2e "$@"
}

cmd_contract() {
  require_env_file
  require_free_ports 3002
  pnpm build:packages
  pnpm -C s3-browser/api build
  DATA_DIR="$(mktemp -d -t s3-browser-contract.XXXXXX)"
  export DATA_DIR PORT=3002
  scripts/live-tests/run-contract-suite.sh
}

cmd_down() {
  scripts/live-tests/stop-garage.sh
  rm -f "$env_file" "/tmp/${GARAGE_CONTAINER_NAME}.toml"
  echo "Garage container $GARAGE_CONTAINER_NAME removed."
}

case "${1:-}" in
  up) cmd_up ;;
  e2e) shift && cmd_e2e "$@" ;;
  contract) cmd_contract ;;
  env) cat "$env_file" ;;
  logs) scripts/live-tests/garage-logs.sh ;;
  down) cmd_down ;;
  *)
    sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'
    exit 2
    ;;
esac
